  "1": "States of matter",
  "2": "Atoms, elements and compounds",
  "3": "Stoichiometry",
  "4": "Electrochemistry",
  "5": "Chemical energetics",
  "6": "Chemical reactions",
  "7": "Acids, bases and salts",
