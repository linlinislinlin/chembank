window.ChemBankPortal = {
  trackOf: function (a) {
    const t = String((a && a.title) || "");
    if (/^\s*(\[?igcse\]?|ig\b|0620)/i.test(t)) return "ig";
    const p = String((a && a.programme) || "").toLowerCase();
    if (p === "ig" || p === "igcse") return "ig";
    return "as";
  },
  roster: function (track) {
    return track === "ig" ? (window.IG_ROSTER || []) : (window.AS_ROSTER || []);
  },
  studentLabel: function (s) {
    const name = (s && s.name) || "Student";
    const klass = (s && s.class_name) || "";
    return klass ? name + " (" + klass + ")" : name;
  },
  classOptions: function (track) {
    if (track === "ig") {
      return [
        { value: "", label: "All IGCSE students" },
        { value: "Q", label: "Qingyun" },
        { value: "T", label: "Tester" },
      ];
    }
    return [
      { value: "", label: "All AS students" },
      { value: "C", label: "Class C" },
      { value: "F", label: "Class F" },
      { value: "T", label: "Tester" },
    ];
  },
  homeHref: function (track) {
    return track === "ig" ? "ig.html" : "as.html";
  },
  topicSlug: function (title, track) {
    const g = this.homeworkGroup(title, track);
    const map = {
      "Chemical Bonding": "bonding",
      "Atomic Structure": "atomic",
      "Energetics": "energetics",
      "States of matter": "states",
      "Atomic structure": "atomic",
      "Periodic table": "periodic",
      "Homework": "hw",
      "Other": "other",
    };
    return map[g] || "other";
  },
  /* --- IGCSE syllabus helpers -------------------------------------------- */
  /* Pull syllabus codes out of a homework title, e.g.
       "IGCSE 2.4 Ions and ionic bonds"     -> ["2.4"]
       "IGCSE 2.1–2.3 Atomic structure..."  -> ["2.1","2.2","2.3"] */
  igCodes: function (title) {
    const t = String(title || "");
    const out = [];
    const add = function (c) { if (out.indexOf(c) < 0) out.push(c); };
    const covered = [];
    let m;
    const rangeRe = /(\d{1,2})\.(\d{1,2})\s*[–—~-]\s*(\d{1,2})\.(\d{1,2})/g;
    while ((m = rangeRe.exec(t))) {
      covered.push([m.index, rangeRe.lastIndex]);
      const u1 = Number(m[1]), s1 = Number(m[2]), u2 = Number(m[3]), s2 = Number(m[4]);
      if (u1 === u2 && s1 <= s2) {
        for (let i = s1; i <= s2; i++) add(u1 + "." + i);
      } else {
        add(u1 + "." + s1);
        add(u2 + "." + s2);
      }
    }
    const oneRe = /(\d{1,2})\.(\d{1,2})/g;
    while ((m = oneRe.exec(t))) {
      const inside = covered.some(function (c) { return m.index >= c[0] && m.index < c[1]; });
      if (!inside) add(m[1] + "." + m[2]);
    }
    return out;
  },
  compressCodes: function (codes) {
    const sorted = (codes || []).slice().sort(function (a, b) {
      return a.localeCompare(b, "en", { numeric: true });
    });
    const out = [];
    let i = 0;
    while (i < sorted.length) {
      const u = Number(sorted[i].split(".")[0]);
      const base = Number(sorted[i].split(".")[1]);
      let j = i;
      while (j + 1 < sorted.length) {
        const p = sorted[j + 1].split(".");
        if (Number(p[0]) === u && Number(p[1]) === base + (j + 1 - i)) j++;
        else break;
      }
      out.push(j > i ? sorted[i] + "–" + sorted[j] : sorted[i]);
      i = j + 1;
    }
    return out.join(", ");
  },
  igUnitOf: function (title) {
    const codes = this.igCodes(title);
    for (let i = 0; i < codes.length; i++) {
      const u = codes[i].split(".")[0];
      if (IG_UNITS[u]) return u;
    }
    return "";
  },
  igGroupLabel: function (title) {
    const u = this.igUnitOf(title);
    return u ? (u + " " + IG_UNITS[u]) : "Other";
  },
  groupRank: function (name) {
    const m = String(name || "").match(/^(\d{1,2})\b/);
    return m ? Number(m[1]) : 999;
  },
  shortCode: function (a) {
    const title = String((a && a.title) || "");
    const track = this.trackOf(a);
    if (track === "ig") {
      const codes = this.igCodes(title);
      return codes.length
        ? ("IG " + this.compressCodes(codes))
        : ("IG " + String((a && a.id) || "x"));
    }
    const slug = this.topicSlug(title, track);
    const m = title.match(/(\d+\.\d+)/);
    const num = m ? m[1] : String((a && a.id) || "x");
    return "AS-" + slug + "-" + num;
  },
  homeworkGroup: function (title, track) {
    const t = title || "";
    if (track === "ig") return this.igGroupLabel(t);
    if (/^3\.\d/.test(t) || /electronegativity|ionic bonding|metallic bonding|sigma\s*\/\s*pi|shapes of molecules|intermolecular/i.test(t)) {
      return "Chemical Bonding";
    }
    if (/^1\.\d/.test(t) || /atomic structure/i.test(t)) return "Atomic Structure";
    if (/^5\.\d/.test(t) || /enthalpy|energetics/i.test(t)) return "Energetics";
    return "Other";
  },
  renderHomeworkList: async function (opts) {
    const box = opts.box;
    const err = opts.err;
    const track = opts.track === "ig" ? "ig" : "as";
    const order = track === "ig"
      ? null
      : ["Chemical Bonding", "Atomic Structure", "Energetics", "Other"];
    try {
      if (!window.HomeworkDB) throw new Error("HomeworkDB missing");
      const all = await window.HomeworkDB.listAssignments();
      const list = (all || []).filter(function (a) {
        if (a.status && a.status !== "published") return false;
        if (/sample/i.test(a.title || "")) return false;
        return window.ChemBankPortal.trackOf(a) === track;
      });
      box.innerHTML = "";
      if (!list.length) {
        box.innerHTML = track === "ig"
          ? '<span class="sub">No IGCSE homework published yet.</span>'
          : '<span class="sub">No AS homework published yet.</span>';
        return;
      }
      const grouped = new Map();
      list.forEach(function (a) {
        const g = window.ChemBankPortal.homeworkGroup(a.title || "", track);
        if (!grouped.has(g)) grouped.set(g, []);
        grouped.get(g).push(a);
      });
      let names;
      if (order) {
        names = order.filter(function (n) { return grouped.has(n); });
        grouped.forEach(function (_v, n) { if (names.indexOf(n) < 0) names.push(n); });
      } else {
        names = Array.from(grouped.keys()).sort(function (a, b) {
          const ra = window.ChemBankPortal.groupRank(a);
          const rb = window.ChemBankPortal.groupRank(b);
          if (ra !== rb) return ra - rb;
          return a.localeCompare(b, "en");
        });
      }
      names.forEach(function (name) {
        const items = grouped.get(name);
        if (!items || !items.length) return;
        items.sort(function (a, b) { return window.ChemBankPortal.shortCode(a).localeCompare(window.ChemBankPortal.shortCode(b), "en", { numeric: true }); });
        const sec = document.createElement("div");
        sec.className = "hw-folder";
        const btn = document.createElement("button");
        btn.type = "button";
        btn.className = "hw-folder-btn";
        btn.innerHTML = "<span class=\"chev\">▶</span><span class=\"lab\"></span><span class=\"count\"></span>";
        btn.querySelector(".lab").textContent = name;
        btn.querySelector(".count").textContent = items.length + (items.length === 1 ? " homework" : " homeworks");
        const ul = document.createElement("div");
        ul.className = "hw-list";
        items.forEach(function (a) {
          const n = (a.question_ids || []).length;
          const link = document.createElement("a");
          link.className = "hw-item";
          link.href = "homework.html?id=" + a.id + "&track=" + track;
          link.innerHTML = "<b></b><div class=\"meta\"></div>";
          link.querySelector("b").textContent = window.ChemBankPortal.shortCode(a);
          link.querySelector(".meta").textContent = (a.title || "") + (n ? " · " + n + " questions" : "");
          ul.appendChild(link);
        });
        btn.addEventListener("click", function () {
          const open = sec.classList.toggle("open");
          btn.querySelector(".chev").textContent = open ? "▼" : "▶";
        });
        sec.appendChild(btn);
        sec.appendChild(ul);
        box.appendChild(sec);
      });
    } catch (e) {
      box.innerHTML = "";
      if (err) err.textContent = "Could not load homework list: " + (e.message || e);
    }
  },
};
